import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {inspect,root,log,model,write,command as c} from './modular-cad.mjs';
import {readNative,writeNative,partitionCurrentDocument,sha256,assertSourceHash,validateStandalone} from './modular-native-history.mjs';
const cli='C:/Program Files/SolidCraft/solidcraft-cli.exe';
if(!process.argv.includes('--prepare'))throw new Error('Use --prepare for isolated verified history migration; live promotion is a separate verified stage');
const runDir=fs.mkdtempSync(path.join(root,'models/experiments/modular-native-'));
const reportDir=path.join(log,path.basename(runDir));fs.mkdirSync(reportDir);
const attempt={runDir,reportDir,status:'running',startedAt:new Date().toISOString()};
write(path.join(log,'native-attempt.json'),attempt);
try {
const [before,tree]=inspect('native-migration-start');
assert(!before.dirty,'Save desktop work before capturing current history');
assert.equal(before.path?.replaceAll('\\','/').toLowerCase(),model('seat-adapter.sc').toLowerCase(),'Expected original assembly active');
const sourceHash=sha256(fs.readFileSync(before.path));
const source=readNative(before.path,path.join(runDir,'current-document.json'));
const masterId=tree.components.find(c=>c.name==='AdapterBody')?.id;
const partition=partitionCurrentDocument(source.document,{masterComponentId:masterId});
assertSourceHash(before.path,sourceHash);
const masterInput=path.join(runDir,'master-history.sc'),master=path.join(runDir,'adapter-body.sc'),replayed=path.join(runDir,'replayed.sc');
writeNative({sourcePath:before.path,outputPath:masterInput,document:partition.masterDocument,expectedSha256:sourceHash});
const migrated=readNative(masterInput,path.join(runDir,'migrated-document.json'));
assert.deepEqual(migrated.inventory.assets,source.inventory.assets,'Embedded source assets changed');
assert.deepEqual(migrated.document.features,partition.masterDocument.features,'Native master definitions changed');
const run=(args,label)=>{
 const r=spawnSync(cli,args,{encoding:'utf8',windowsHide:true,timeout:240000});
 fs.writeFileSync(path.join(reportDir,label+'.txt'),r.stderr||r.stdout||'');
 assert.equal(r.status,0,r.stderr||r.error?.message||label+' failed');
};
const nativeReport=path.join(reportDir,'native-master-rebuild.json'),replayReport=path.join(reportDir,'native-master-replay.json');
run(['run',masterInput,'--save',master,'--json-out',nativeReport],'native-master-rebuild');
const script=path.join(runDir,'adapter-body-build.json');
run(['script',master,'--out',script],'native-master-export');
const omitted=fs.readFileSync(path.join(reportDir,'native-master-export.txt'),'utf8');
const omissionLines=omitted.split(/\r?\n/).filter(line=>line.includes('leaves out'));
assert(omissionLines.every(line=>line.trim()==='note: the script leaves out appearances (colours of bodies and faces)'),'Exporter omitted model history: '+omitted);
run(['run',script,'--save',replayed,'--json-out',replayReport],'native-master-replay');
const healthScript=path.join(runDir,'health.json');
write(healthScript,{commands:[c('document.inspect',{measure:true,timeline:'summary'}),c('model.faces',{body:'AdapterBodyMaster'}),c('file.export',{path:path.join(runDir,'master.stl'),bodies:['AdapterBodyMaster']})]});
const healthPath=path.join(reportDir,'native-master-health.json');
run(['run',healthScript,'--in',master,'--results','--json-out',healthPath],'native-master-health');
const healthResults=JSON.parse(fs.readFileSync(healthPath,'utf8')),health=healthResults[0];
const faces=healthResults[1].faces??healthResults[1];
assert.equal(faces.filter(f=>f.cylinder&&Math.abs(f.cylinder.radius-20)<1e-6).length,2,'Two analytic R20 cylinders required');
const ceilingsPath=path.join(reportDir,'native-master-ceilings.json');
const ceilingRun=spawnSync(process.execPath,[path.join(root,'scripts/validate-mounting-ceilings.mjs'),path.join(runDir,'master.stl'),ceilingsPath],{encoding:'utf8',windowsHide:true,timeout:60000});
assert.equal(ceilingRun.status,0,ceilingRun.stderr||ceilingRun.stdout);
const result={baseline:{bodies:before.bodies},rebuilt:JSON.parse(fs.readFileSync(nativeReport)),replayed:JSON.parse(fs.readFileSync(replayReport)),features:health.timeline.length,healthy:health.timeline.every(f=>!f.error&&!f.warning),assetsMatch:true};
const verification=validateStandalone(result);assertSourceHash(before.path,sourceHash);
const report={...verification,sourceHash,sourcePath:before.path,runDir,reportDir,master,script,replayed,analyticR20:2,ceilingChecks:JSON.parse(fs.readFileSync(ceilingsPath)).checks,assetInventory:source.inventory.assets,printingFeatures:partition.printingFeatures.map(f=>({id:f.id,name:f.name})),...result};
write(path.join(reportDir,'validation.json'),report);write(path.join(log,'native-history-validation.json'),report);
write(path.join(log,'current-run.json'),{runDir,reportDir,master,script,replayed,sourceHash,sourcePath:before.path,documentHash:sha256(fs.readFileSync(path.join(runDir,'current-document.json'))),masterHash:sha256(fs.readFileSync(master))});
write(path.join(log,'native-attempt.json'),{...attempt,status:'complete',finishedAt:new Date().toISOString()});
console.log(JSON.stringify({ok:true,runDir,master,features:health.timeline.length}));
} catch(error){
 write(path.join(log,'native-attempt.json'),{...attempt,status:'failed',finishedAt:new Date().toISOString(),error:error.message});
 throw error;
}
