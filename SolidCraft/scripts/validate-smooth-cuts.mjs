import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,root)));
const unpack=r=>JSON.parse(r.content[0].text);
const result=read('logs/smooth-verification.json').map(unpack);
const [test,measure,childTopology,design,tree]=result;
const after=read('logs/smooth-after.json').map(unpack);
const assert=(v,m)=>{if(!v)throw new Error(m);};
const masterCylinders=after[2].cylinders.filter(c=>Math.abs(c.radius-20)<1e-6);
const childCylinders=childTopology.cylinders.filter(c=>Math.abs(c.radius-20)<1e-6);
assert(masterCylinders.length===2&&childCylinders.length===2,'Both master/child need two analytic R20 cylinders');
const sub=(a,b)=>a.map((v,i)=>v-b[i]);
const dot=(a,b)=>a.reduce((s,v,i)=>s+v*b[i],0);
const cross=(a,b)=>[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
const norm=a=>Math.sqrt(dot(a,a));
const mirror=a=>[-a[0],a[1],a[2]];
const [a,b]=masterCylinders;
const axisParallelError=1-Math.abs(dot(mirror(a.axis),b.axis));
const mirroredAxisDistanceMm=norm(cross(sub(mirror(a.origin),b.origin),b.axis));
assert(Math.abs(axisParallelError)<1e-9&&mirroredAxisDistanceMm<1e-6,'Cylinder axes are not mirror images');
const sideSketches=after[3].sketches.filter(s=>s.name==='M17_SeatSideProfile'||s.name==='M17_SeatSideReflectedProfile');
assert(sideSketches.length===2&&sideSketches.every(s=>s.curves.length===1&&s.curves[0].type==='circle'),'Polygon geometry remains');
const bodies=measure.bodies.filter(b=>['AdapterBodyMaster','AdapterBodyFront','AdapterBodyRear'].includes(b.name));
assert(bodies.length===3&&bodies.every(b=>b.closed),'Manufactured solids are missing/open');
assert(design.timeline.length===72&&design.timeline.every(f=>!f.error&&!f.warning),'Feature health/count');
assert(design.sketches.length===25&&design.sketches.every(s=>s.dof===0),'Sketch freedom');
assert(test.restored&&test.errors.length===0&&test.parameter_errors.length===0,'Parameter test did not restore cleanly');
const delta=n=>test.measure.bodies.find(b=>b.name===n).volume_mm3-bodies.find(b=>b.name===n).volume_mm3;
assert(delta('AdapterBodyMaster')<0&&Math.abs(delta('AdapterBodyMaster')-delta('AdapterBodyFront')-delta('AdapterBodyRear'))<1e-5,'Child does not inherit');
const c=n=>tree.components.find(c=>c.name===n),container=tree.components.find(c=>c.id===0);
assert(container.bodies.length===0&&container.sketches.length===0&&['AdapterBody','AdapterBodySplit','WheelScanReference'].every(n=>c(n)?.parent===0),'Component hierarchy changed');
assert(read('logs/mounting-ceiling-validation.json').ok,'Mounting ceilings failed');
const script=read('scripts/seat-adapter-build.json').commands;
assert(script.findIndex(c=>c.params.name==='M17_MirrorSmoothHalf')<script.findIndex(c=>c.params.name==='M21_WheelImprint'),'Wheel imprint must follow symmetry reconstruction');
assert(!script.some(c=>c.command==='sketch.line'&&c.params.points?.length===256),'Faceted cutter remains in replay');
const report={ok:true,checkedAt:new Date().toISOString(),checkpointCommit:'fc7f175',features:72,fixedSketches:25,manufacturedBodies:bodies.map(b=>({name:b.name,volumeMm3:b.volume_mm3,closed:b.closed,faces:b.faces})),masterCylinders,childCylinders,axisParallelError,mirroredAxisDistanceMm,noPolygonProfile:true,inheritance:{restored:true,masterDeltaMm3:delta('AdapterBodyMaster'),childDeltaMm3:delta('AdapterBodyFront')+delta('AdapterBodyRear')},mountingCeilingChecks:12,errors:[],warnings:[],onshapeApiCalls:0};
fs.writeFileSync(new URL('logs/smooth-cut-validation.json',root),JSON.stringify(report,null,2));
console.log(JSON.stringify({ok:true,analyticR20Cylinders:2,mirroredAxisDistanceMm,manufacturedSolids:3,features:72,noFacets:true,inheritance:true,ceilingChecks:12}));
