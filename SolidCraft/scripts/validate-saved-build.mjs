import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const unpack=r=>JSON.parse(r.content[0].text);
const report=read('logs/build-validation.json');
const original=read('logs/open-final.json');
const state=unpack(original[2]);
const test=read('logs/inheritance-test.json').map(unpack);
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
assert(report.master.closed&&report.child.bodies.length===2&&report.child.bodies.every(b=>b.closed),'Closed master/two-child solids');
assert(state.timeline.every(f=>!f.error&&!f.warning),'Timeline health');
assert(state.sketches.length===25&&state.sketches.every(s=>s.dof===0),'Fixed sketches');
assert(!state.timeline.some(f=>/fillet/i.test(f.type)),'No fillets');
assert(test[0].restored&&test[0].errors.length===0&&test[0].parameter_errors.length===0,'Inheritance test restored cleanly');
const baseline=Object.fromEntries(test[1].bodies.map(b=>[b.name,b.volume_mm3]));
const changed=Object.fromEntries(test[0].measure.bodies.map(b=>[b.name,b.volume_mm3]));
const dm=changed.AdapterBodyMaster-baseline.AdapterBodyMaster;
const dc=changed.AdapterBodyFront+changed.AdapterBodyRear-baseline.AdapterBodyFront-baseline.AdapterBodyRear;
assert(dm<0&&Math.abs(dm-dc)<1e-5,'Master/child dependency');
const ceiling=read('logs/mounting-ceiling-validation.json');
assert(ceiling.ok&&ceiling.checks.length===12&&ceiling.checks.every(c=>c.ok),'Mounting ledges and access');
const script=read('scripts/seat-adapter-build.json');
assert(script.commands.filter(c=>c.command==='solid.extrude'&&c.params.name?.startsWith('C03_')).length===5,'Five connector features');
assert(script.commands.some(c=>c.params.name==='M21_WheelImprint'),'Wheel imprint');
for(const name of ['models/seat-adapter.sc','models/adapter-body-native.sc','models/adapter-body-imprinted.sc','exports/adapter-body.step','exports/adapter-body.stl','exports/adapter-front.stl','exports/adapter-rear.stl','exports/adapter-body-split.step','exports/adapter-body-split.3mf'])assert(fs.statSync(path.join(root,name)).size>100,'Missing/empty artifact '+name);
assert(read('logs/exports.json').every(r=>!r.isError),'Export tool results');
console.log(JSON.stringify({ok:true,closedSolids:3,features:state.timeline.length,fixedSketches:25,connectorCuts:5,ceilingChecks:12,inheritanceDeltaMm3:dm,exactOnshapeParity:false,source:'Saved live inspections, restored parameter experiment, STL material tests and nonempty native/export artifacts'}));
